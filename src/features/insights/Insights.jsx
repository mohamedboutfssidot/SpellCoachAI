import { useState } from 'react'
import { askCoach } from '../../lib/coach.js'
import { analyze, localPlan, TYPE_LABEL } from './analyze.js'

export default function Insights({ log, onReset }) {
  const a = analyze(log)
  const [plan, setPlan] = useState(null)
  const [loading, setLoading] = useState(false)
  const max = a.errorList[0]?.[1] || 1
  const trend = a.recentRate !== null && a.previousRate !== null ? a.recentRate - a.previousRate : null

  const makePlan = async () => {
    setLoading(true)
    try {
      // Only aggregated statistics leave the browser (not the full log).
      const data = await askCoach({
        mode: 'plan',
        stats: { attempts: a.attempts, accuracy: a.accuracy, errors: a.errors, hardWords: a.hardWords.map(x => x.w) },
      })
      if (!data.tips?.length) throw new Error('empty')
      setPlan(data)
    } catch {
      setPlan(localPlan(a))
    }
    setLoading(false)
  }

  if (a.attempts === 0) {
    return (
      <section className="desk">
        <p className="prompt">No data yet. Do a few word dictations, then come back here.</p>
      </section>
    )
  }

  return (
    <section className="desk" aria-label="Progress">
      <p className="prompt">
        {a.attempts} answers · {a.accuracy}% accuracy
        {trend !== null && (
          <span className={trend >= 0 ? 'trend up' : 'trend down'}>
            {' '}· {trend >= 0 ? '+' : ''}{trend} pts over the last 10
          </span>
        )}
      </p>

      <p className="row-label">Latest answers</p>
      <div className="dots" role="img" aria-label="History of the latest answers">
        {log.slice(-30).map((e, i) => <span key={i} className={e.ok ? 'dot ok' : 'dot bad'} title={e.w} />)}
      </div>

      {a.errorList.length > 0 && (
        <>
          <p className="row-label">Error types</p>
          <div className="bars">
            {a.errorList.map(([type, n]) => (
              <div className="bar-row" key={type}>
                <span>{TYPE_LABEL[type]}</span>
                <div className="bar"><i style={{ width: `${(n / max) * 100}%` }} /></div>
                <b>{n}</b>
              </div>
            ))}
          </div>
        </>
      )}

      {a.hardWords.length > 0 && (
        <>
          <p className="row-label">Hardest words</p>
          <div className="chips">
            {a.hardWords.map(x => <span className="chip" key={x.w}>{x.w} ×{x.n}</span>)}
          </div>
        </>
      )}

      <div className="actions" style={{ marginTop: 22 }}>
        <button className="primary" onClick={makePlan} disabled={loading || a.attempts < 3}>
          {loading ? 'Analysing…' : 'My study plan'}
        </button>
        <button className="chip" onClick={onReset}>Reset</button>
        {a.attempts < 3 && <span className="keys">At least 3 answers needed</span>}
      </div>

      {plan && (
        <aside className="coach good" aria-live="polite">
          <p className="verdict">{plan.summary}</p>
          <ol className="plan">
            {plan.tips.map((t, i) => (
              <li key={i}><strong>{t.title}</strong><span>{t.advice}</span></li>
            ))}
          </ol>
          <p className="source">{plan.source === 'ai' ? 'Plan generated by the AI model' : 'Local plan (AI unavailable)'}</p>
        </aside>
      )}
    </section>
  )
}
